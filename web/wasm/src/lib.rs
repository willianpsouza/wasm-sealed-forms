//! wasm_sealed_forms
//!
//! Browser-side sealing for PII-heavy forms. Given the form as a JSON string it:
//!   1. signs the canonical JSON bytes with an embedded Ed25519 key,
//!   2. seals (ECDH x25519 + XChaCha20-Poly1305) the signed form to the
//!      backend's public key, producing an opaque base64 envelope.
//!
//! The envelope is what leaves the browser. Any TLS-terminating intermediary on
//! the path — API gateway, reverse proxy, CDN, WAF, access logs — sees only
//! ciphertext. Only the backend, holder of the x25519 secret, can read it.
//!
//! SECURITY: the Ed25519 key is embedded in client code and is extractable, so
//! the signature does NOT authenticate the submitter. The real guarantee is
//! confidentiality from intermediaries. See README threat model.

mod keys_gen; // generated by `go run ./cmd/genkeys` (git-ignored)

use base64::{engine::general_purpose::STANDARD as B64, Engine as _};
use chacha20poly1305::{aead::Aead, aead::Payload, KeyInit, XChaCha20Poly1305, XNonce};
use ed25519_dalek::{Signer, SigningKey};
use hkdf::Hkdf;
use rand_core::{OsRng, RngCore};
use serde::Serialize;
use sha2::{Digest, Sha256};
use wasm_bindgen::prelude::*;
use x25519_dalek::{EphemeralSecret, PublicKey};

const HKDF_INFO: &[u8] = b"wasm-sealed-forms-v1";

#[derive(Serialize)]
struct Sealed {
    body_b64: String,
    sig_b64: String,
}

#[derive(Serialize)]
struct Output {
    /// SHA-256 of the plaintext form (client-side integrity receipt).
    digest: String,
    /// Size of the plaintext form in bytes.
    bytes: usize,
    /// Opaque base64 envelope to POST to the backend.
    payload: String,
}

/// Sign + seal `form_json` and return JSON `{digest, bytes, payload}`.
/// Rejects input that is not a JSON object.
///
/// Thin wasm-bindgen wrapper. All logic is in `seal_submission_inner` with
/// `String` errors, so it is unit-testable on the host without constructing a
/// `JsValue` (which aborts off the wasm target).
#[wasm_bindgen]
pub fn seal_submission(form_json: &str) -> Result<String, JsValue> {
    seal_submission_inner(form_json).map_err(|e| JsValue::from_str(&e))
}

fn seal_submission_inner(form_json: &str) -> Result<String, String> {
    let value: serde_json::Value = serde_json::from_str(form_json).map_err(|e| e.to_string())?;
    if !value.is_object() {
        return Err("form must be a JSON object".into());
    }
    let body = form_json.as_bytes();

    // --- sign the canonical form bytes with the embedded Ed25519 key ---
    let signing = SigningKey::from_bytes(&keys_gen::ED25519_SEED);
    let sig = signing.sign(body);

    let sealed = Sealed {
        body_b64: B64.encode(body),
        sig_b64: B64.encode(sig.to_bytes()),
    };
    let plaintext = serde_json::to_vec(&sealed).map_err(|e| e.to_string())?;

    // --- seal to the backend's x25519 public key (anonymous sender) ---
    let envelope = seal_to_backend(&plaintext)?;

    let out = Output {
        digest: hex(&Sha256::digest(body)),
        bytes: body.len(),
        payload: B64.encode(&envelope),
    };
    serde_json::to_string(&out).map_err(|e| e.to_string())
}

/// envelope = ephemeral_pub(32) || nonce(24) || ciphertext
fn seal_to_backend(plaintext: &[u8]) -> Result<Vec<u8>, String> {
    let server_pub = PublicKey::from(keys_gen::SERVER_X25519_PUB);

    let eph_secret = EphemeralSecret::random_from_rng(OsRng);
    let eph_pub = PublicKey::from(&eph_secret);
    let shared = eph_secret.diffie_hellman(&server_pub);

    let hk = Hkdf::<Sha256>::new(None, shared.as_bytes());
    let mut key = [0u8; 32];
    hk.expand(HKDF_INFO, &mut key)
        .map_err(|_| "hkdf expand failed".to_string())?;

    let cipher = XChaCha20Poly1305::new((&key).into());
    let mut nonce_bytes = [0u8; 24];
    OsRng.fill_bytes(&mut nonce_bytes);
    let nonce = XNonce::from_slice(&nonce_bytes);

    let ct = cipher
        .encrypt(
            nonce,
            Payload {
                msg: plaintext,
                aad: eph_pub.as_bytes(),
            },
        )
        .map_err(|_| "aead encrypt failed".to_string())?;

    let mut envelope = Vec::with_capacity(32 + 24 + ct.len());
    envelope.extend_from_slice(eph_pub.as_bytes());
    envelope.extend_from_slice(&nonce_bytes);
    envelope.extend_from_slice(&ct);
    Ok(envelope)
}

fn hex(bytes: &[u8]) -> String {
    let mut s = String::with_capacity(bytes.len() * 2);
    for b in bytes {
        s.push_str(&format!("{b:02x}"));
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn seal_structure_and_freshness() {
        let a = seal_to_backend(b"hello world").expect("seal a");
        let b = seal_to_backend(b"hello world").expect("seal b");
        assert!(a.len() >= 32 + 24 + 16);
        assert_ne!(a, b);
        assert_ne!(&a[..32], &b[..32], "ephemeral public key must differ");
    }

    #[test]
    fn seal_submission_outputs_digest_and_payload() {
        let form = r#"{"full_name":"Ana Silva","cpf":"000.000.000-00","bank_account":"1234-5"}"#;
        let out = seal_submission_inner(form).unwrap();
        let v: serde_json::Value = serde_json::from_str(&out).unwrap();
        assert_eq!(v["bytes"].as_u64().unwrap(), form.len() as u64);
        assert_eq!(v["digest"].as_str().unwrap().len(), 64); // sha256 hex
        assert!(v["payload"].as_str().unwrap().len() > 50);
        // the ciphertext must NOT contain the plaintext PII
        assert!(!v["payload"].as_str().unwrap().contains("Ana"));
    }

    #[test]
    fn seal_submission_rejects_non_object() {
        assert!(seal_submission_inner("[1,2,3]").is_err());
        assert!(seal_submission_inner("not json").is_err());
        assert!(seal_submission_inner("\"just a string\"").is_err());
    }

    #[test]
    fn signs_with_embedded_key() {
        use ed25519_dalek::{Verifier, VerifyingKey};
        let signing = SigningKey::from_bytes(&keys_gen::ED25519_SEED);
        let msg = b"form bytes";
        let sig = signing.sign(msg);
        let vk: VerifyingKey = signing.verifying_key();
        assert!(vk.verify(msg, &sig).is_ok());
    }

    #[test]
    fn hex_encodes() {
        assert_eq!(hex(&[0x00, 0x0f, 0xff]), "000fff");
    }
}
